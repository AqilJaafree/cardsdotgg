// Generates src/engine/CardData.sol from shared/cards.json. Run: node contracts/script/gen-carddata.mjs
import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../../", import.meta.url);
const { cards } = JSON.parse(readFileSync(new URL("shared/cards.json", root)));
for (const c of cards) if (c.hp + c.atk + c.def + c.spd !== 100) throw new Error(`${c.name} stats != 100`);
const hex = (n) => n.toString(16).padStart(2, "0");
const stats = cards.map((c) => hex(c.hp) + hex(c.atk) + hex(c.def) + hex(c.spd)).join("");
const names = cards.map((c) => `        if (id == ${c.id}) return "${c.name}";`).join("\n");
const classes = cards.map((c) => `        if (id == ${c.id}) return "${c.assetClass}";`).join("\n");
writeFileSync(new URL("contracts/src/engine/CardData.sol", root), `// SPDX-License-Identifier: MIT
// GENERATED by script/gen-carddata.mjs from shared/cards.json. Do not edit.
pragma solidity ^0.8.24;

library CardData {
    bytes internal constant STATS = hex"${stats}";

    function stats(uint8 id) internal pure returns (uint8 hp, uint8 atk, uint8 def, uint8 spd) {
        uint256 i = uint256(id) * 4;
        bytes memory s = STATS;
        return (uint8(s[i]), uint8(s[i + 1]), uint8(s[i + 2]), uint8(s[i + 3]));
    }

    function name(uint8 id) internal pure returns (string memory) {
${names}
        revert("card");
    }

    function assetClass(uint8 id) internal pure returns (string memory) {
${classes}
        revert("card");
    }
}
`);
